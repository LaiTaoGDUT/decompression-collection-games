#!/usr/bin/env python3
"""Read final theme atlas alpha and emit normalized hit contours, retaining openings."""
import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('contours', ROOT / 'project-scripts/generate-desktop-cleanup-hit-polygons.py')
contours = importlib.util.module_from_spec(spec)
spec.loader.exec_module(contours)


def item_names(theme):
    """Use the runtime theme's atlas order; do not duplicate it in production docs."""
    executable = shutil.which('tsc')
    if not executable:
        raise SystemExit('需要 TypeScript 编译器 tsc 来读取主题物品顺序。')
    compiler = Path(executable).resolve().parent.parent / 'lib/typescript.js'
    script = """
const fs = require('node:fs');
const [compiler, file, name] = process.argv.slice(1);
const ts = require(compiler);
const sf = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
if (sf.parseDiagnostics.length) throw new Error('主题文件语法错误：' + file);
const declaration = sf.statements.filter(ts.isVariableStatement)
    .flatMap(statement => Array.from(statement.declarationList.declarations))
    .find(node => ts.isIdentifier(node.name) && node.name.text === name);
let value = declaration?.initializer;
if (value && ts.isCallExpression(value) && value.expression.getText(sf) === 'Object.freeze') value = value.arguments[0];
while (value && (ts.isAsExpression(value) || ts.isParenthesizedExpression(value))) value = value.expression;
if (!value || !ts.isArrayLiteralExpression(value) || !value.elements.every(ts.isStringLiteral)) {
    throw new Error('物品顺序必须是字符串数组：' + name);
}
console.log(JSON.stringify(Array.from(value.elements, element => element.text)));
"""
    file = ROOT / 'assets/games/catch/scripts/DesktopCleanupTheme.ts'
    result = subprocess.run(['node', '-e', script, str(compiler), str(file),
                             f'DESKTOP_CLEANUP_{theme.upper()}_ITEM_TYPES'],
                            cwd=ROOT, check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


def generate(theme):
    names = item_names(theme)
    cell = 384
    if len(names) != 20 or len(set(names)) != len(names):
        raise SystemExit('物品顺序必须与 4 × 5 图集的 20 个不同物品一致。')
    with Image.open(ROOT / f'assets/game-assets/catch/visual/items/desktop-cleanup-{theme}-atlas-v1.png') as source:
        image = source.convert('RGBA')
    if image.size != (4 * cell, 5 * cell):
        raise SystemExit(f'图集尺寸与 4 × 5 个 {cell}px 格子不一致：{image.size}')
    alpha = image.getchannel('A').tobytes()
    # Regenerated sprites include semitransparent cast shadows; only opaque bodies receive input.
    command = 'project-scripts/desktop-cleanup/generate-dessert-hit-shapes.py' + (f' {theme}' if theme != 'dessert' else '')
    lines = [f'// Generated by {command}; do not hand-edit.',
             '// Coordinates normalized to each 384px cell; alpha >= 240, RDP 1.2px.',
             f'export const DESKTOP_CLEANUP_{theme.upper()}_HIT_SHAPES = Object.freeze({{']
    manifest = {}
    for i, name in enumerate(names):
        component = contours.largest_component(alpha, image.width, i % 4 * cell, i // 4 * cell, cell, cell, 240)
        try:
            loops = contours.boundary_loops(component, cell, cell)
        except ValueError:
            component = contours.close_boundary_gaps(component, cell, cell)
            loops = contours.boundary_loops(component, cell, cell)
        loops.sort(key=lambda loop: abs(contours.polygon_area(loop)), reverse=True)
        # Ignore tiny texture pinholes. The actual ring opening is retained.
        loops = [loops[0]] + [loop for loop in loops[1:] if abs(contours.polygon_area(loop)) >= 100]
        shapes = [contours.simplify_open_polygon(loop, 1.2)[:-1] for loop in loops]
        assert all(len(p) >= 3 for p in shapes)

        def render(points):
            return 'Object.freeze([' + ', '.join(f'Object.freeze({{ x: {x / cell:.6f}, y: {y / cell:.6f} }})' for x, y in points) + '])'

        lines += [f"    '{name}': Object.freeze({{", f'        outer: {render(shapes[0])},',
                  '        holes: Object.freeze([' + ', '.join(render(p) for p in shapes[1:]) + ']),', '    }),']
        manifest[name] = {'outerVertices': len(shapes[0]), 'holes': len(shapes) - 1}
    lines += ['});', '']
    hole_item = {'dessert': 'strawberry-doughnut', 'convenience': 'golden-shopping-basket'}.get(theme)
    if hole_item:
        assert manifest[hole_item]['holes'] >= 1, f'{hole_item} opening must remain clickable-through'
    return '\n'.join(lines), manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('theme', choices=('dessert', 'convenience', 'fruit'), nargs='?', default='dessert')
    parser.add_argument('--output', type=Path, help='TypeScript 输出路径，默认更新当前主题的 HitShapes.ts')
    parser.add_argument('--report', type=Path, help='可选的轮廓顶点和孔洞统计 JSON')
    args = parser.parse_args()
    output = args.output or ROOT / f'assets/games/catch/scripts/DesktopCleanup{args.theme.title()}HitShapes.ts'
    source, manifest = generate(args.theme)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Generated {len(manifest)} {args.theme} alpha contours; preserved holes:',
          sum(item['holes'] for item in manifest.values()))


if __name__ == '__main__':
    main()
