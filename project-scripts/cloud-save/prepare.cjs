'use strict';

const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');

function typescript() {
    for (const name of [process.env.COCOS_TYPESCRIPT_PATH, 'typescript',
        '/Applications/Cocos/Creator/3.8.8/CocosCreator.app/Contents/Resources/app.asar.unpacked/node_modules/typescript'].filter(Boolean)) {
        try { return require(name); } catch (error) { if (error.code !== 'MODULE_NOT_FOUND') throw error; }
    }
    throw new Error('找不到 TypeScript；请设置 COCOS_TYPESCRIPT_PATH 为 Cocos 3.8.8 的 TypeScript 目录。');
}

function prepare(check = false) {
    const ts = typescript(), output = path.join(root, 'cloudfunctions/cloudSave/generated');
    const files = {};
    for (const name of ['CloudSaveCodec', 'CloudSaveProjection']) {
        const source = fs.readFileSync(path.join(root, `assets/services/cloud/${name}.ts`), 'utf8');
        files[`${name}.js`] = '// Generated by npm run prepare:cloud-save; edit the TypeScript source.\n'
            + ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.CommonJS,
                newLine: ts.NewLineKind.LineFeed } }).outputText;
    }
    files['catalog.json'] = JSON.stringify(JSON.parse(fs.readFileSync(path.join(root, 'assets/resources/configs/cloud-save.json'), 'utf8'))) + '\n';
    for (const [name, contents] of Object.entries(files)) {
        const destination = path.join(output, name);
        if (check) {
            if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== contents)
                throw new Error(`${name} 已过期，请运行 npm run prepare:cloud-save`);
        } else {
            fs.mkdirSync(output, { recursive: true }); fs.writeFileSync(destination, contents);
        }
    }
    return output;
}

function prepareWeChatProject(directory) {
    const project = path.resolve(directory), configPath = path.join(project, 'project.config.json');
    const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
    const functionRoot = config.cloudfunctionRoot || 'cloudfunctions/';
    if (path.isAbsolute(functionRoot) || functionRoot.split(/[\\/]/).includes('..'))
        throw new Error('cloudfunctionRoot 必须位于微信工程内。');
    const destination = path.join(project, functionRoot, 'cloudSave');
    const source = path.join(root, 'cloudfunctions/cloudSave');
    // 只复制明确的部署文件，不带 node_modules、本地工具或测试；不会修改游戏运行代码。
    for (const relative of ['index.js', 'handler.js', 'package.json', 'config.json',
        'generated/CloudSaveCodec.js', 'generated/CloudSaveProjection.js', 'generated/catalog.json']) {
        const target = path.join(destination, relative);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(path.join(source, relative), target);
    }
    config.cloudfunctionRoot = functionRoot;
    config.packOptions ??= {};
    config.packOptions.ignore ??= [];
    const ignored = functionRoot.replace(/\/$/, '');
    if (!config.packOptions.ignore.some(rule => rule.type === 'folder' && rule.value.replace(/\/$/, '') === ignored))
        config.packOptions.ignore.push({ type: 'folder', value: ignored });
    fs.writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n');
    return destination;
}

if (require.main === module) {
    prepare(process.argv.includes('--check'));
    const index = process.argv.indexOf('--wechat-project');
    if (index >= 0) {
        if (!process.argv[index + 1]) throw new Error('--wechat-project 后需要微信构建产物目录。');
        console.log(`Cloud function copied to ${prepareWeChatProject(process.argv[index + 1])}`);
    } else console.log('Cloud save deployment files ready.');
}
module.exports = { prepare, prepareWeChatProject, typescript, root };
