'use strict';

const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');

function typescript() {
    for (const name of [process.env.COCOS_TYPESCRIPT_PATH, 'typescript',
        '/Applications/Cocos/Creator/3.8.8/CocosCreator.app/Contents/Resources/app.asar.unpacked/node_modules/typescript'].filter(Boolean)) {
        try { return require(name); } catch (error) { if (error.code !== 'MODULE_NOT_FOUND') throw error; }
    }
    throw new Error('找不到 TypeScript；请设置 COCOS_TYPESCRIPT_PATH 为 Cocos 3.8.8 的 TypeScript 目录。');
}

function prepare(check = false) {
    const ts = typescript(), output = path.join(root, 'server/decompression-api/generated');
    const files = {};
    for (const name of ['CloudSaveCodec', 'CloudSaveProjection']) {
        const source = fs.readFileSync(path.join(root, `assets/services/cloud/${name}.ts`), 'utf8');
        files[`${name}.js`] = '// Generated by npm run prepare:server; edit the TypeScript source.\n'
            + ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.CommonJS,
                newLine: ts.NewLineKind.LineFeed } }).outputText;
    }
    files['catalog.json'] = JSON.stringify(JSON.parse(fs.readFileSync(path.join(root, 'assets/resources/configs/cloud-save.json'), 'utf8'))) + '\n';
    const games = JSON.parse(fs.readFileSync(path.join(root, 'assets/resources/configs/games.json'), 'utf8')).games;
    files['games.json'] = JSON.stringify(games.map(game => game.id)) + '\n';
    files['game-labels.json'] = JSON.stringify(Object.fromEntries(games.map(game => [game.id, game.name]))) + '\n';
    for (const [name, contents] of Object.entries(files)) {
        const destination = path.join(output, name);
        if (check) {
            if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== contents)
                throw new Error(`${name} 已过期，请运行 npm run prepare:server`);
        } else {
            fs.mkdirSync(output, { recursive: true }); fs.writeFileSync(destination, contents);
        }
    }
    return output;
}

if (require.main === module) {
    prepare(process.argv.includes('--check'));
    console.log('Game API shared protocol ready.');
}
module.exports = { prepare, typescript, root };
